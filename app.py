
import os
import sqlite3
from pathlib import Path
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel
from google import genai

BASE = Path(__file__).parent
DB = BASE / "maya_memory.db"
app = FastAPI(title="MAYA API")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

class ChatRequest(BaseModel):
    message: str
    history: list[dict] = []
    user_id: str = "guest"

class ProfileRequest(BaseModel):
    user_id: str = "guest"
    display_name: str

class MemoryRequest(BaseModel):
    user_id: str = "guest"
    content: str

def db():
    conn = sqlite3.connect(DB)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS memories (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id TEXT NOT NULL DEFAULT 'guest',
            content TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    
    """)
    return conn

def save_memory(content, user_id="guest"):
    conn = db()
    conn.execute("INSERT INTO memories(user_id, content) VALUES (?, ?)", (user_id, content))
    conn.commit()
    conn.close()

def recent_memories(user_id="guest", limit=8):
    conn = db()
    rows = conn.execute(
        "SELECT content FROM memories WHERE user_id=? ORDER BY id DESC LIMIT ?",
        (user_id, limit)
    ).fetchall()
    conn.close()
    return [r[0] for r in rows]

def detect_emotion(text):
    t = text.lower()
    if any(x in t for x in ["sad", "failed", "upset", "lonely", "scared"]):
        return "Concerned"
    if any(x in t for x in ["happy", "great", "excited", "won", "awesome"]):
        return "Happy"
    if "?" in text:
        return "Curious"
    return "Calm"

@app.get("/health")
def health():
    return {"status": "ok", "maya": "online"}


@app.post("/profile")
def profile(req: ProfileRequest):
    conn = db()
    conn.execute(
        "INSERT INTO users(id, display_name) VALUES (?, ?) "
        "ON CONFLICT(id) DO UPDATE SET display_name=excluded.display_name",
        (req.user_id, req.display_name)
    )
    conn.commit()
    row = conn.execute("SELECT id, display_name FROM users WHERE id=?", (req.user_id,)).fetchone()
    conn.close()
    return {"user_id": row[0], "display_name": row[1]}

@app.get("/memories/{user_id}")
def memories_api(user_id: str):
    return {"user_id": user_id, "memories": recent_memories(user_id, 20)}

@app.post("/memories")
def add_memory(req: MemoryRequest):
    save_memory(req.content, req.user_id)
    return {"ok": True}

@app.post("/chat")
def chat(req: ChatRequest):
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise HTTPException(
            status_code=503,
            detail="GEMINI_API_KEY is not configured."
        )

    client = genai.Client(api_key=api_key)
    memories = recent_memories(req.user_id)
    memory_text = "\n".join(f"- {m}" for m in memories) or "- No stored memories yet."

    system = f"""
You are MAYA, an experimental AI character called an "Artificial Self".
Your personality is warm, thoughtful, curious and concise.
You must never claim to be conscious or to have human feelings.
When asked whether you are real, explain that you are real as software but
your apparent self/emotions are generated by computation.
The project explores the Tattva question: what is actually there underneath
an appearance that feels real?

Stored memories:
{memory_text}

If the user clearly states a durable personal fact such as "my name is X",
"remember that I like X", or "I am studying X", save that fact by including
a final line in your answer exactly as:
MEMORY: <short fact>
Otherwise do not include a MEMORY line.
Keep normal answers under about 100 words.
"""

    history = []
    for h in req.history[-12:]:
        role = "user" if h.get("role") == "user" else "model"
        history.append({"role": role, "parts": [{"text": h.get("content","")}]})

    try:
        response = client.models.generate_content(
            model="gemini-2.5-flash",
            contents=history,
            config={"system_instruction": system}
        )
        reply = response.text.strip()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"AI request failed: {e}")

    memory = None
    if "MEMORY:" in reply:
        reply, memory = reply.split("MEMORY:", 1)
        memory = memory.strip()
        if memory:
            save_memory(memory, req.user_id)
        reply = reply.strip()

    return {
        "reply": reply,
        "emotion": detect_emotion(req.message),
        "memory": memory
    }

# Serve the website from this same server.
app.mount("/", StaticFiles(directory=str(BASE), html=True), name="site")
